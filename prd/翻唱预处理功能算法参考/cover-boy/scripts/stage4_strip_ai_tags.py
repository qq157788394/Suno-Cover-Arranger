def run_self_test():
    logger.info("🧪 运行自检...")

    if not check_ffmpeg():
        logger.error("❌ ffmpeg 未找到")
        return False
    logger.info("✅ ffmpeg 可用")

    try:
        import mutagen
        logger.info(f"✅ mutagen {mutagen.version_string} 可用")
    except ImportError:
        logger.warning("⚠️ mutagen 未安装，智能模式不可用")

    tmp_dir = Path(tempfile.mkdtemp(prefix="ai_tag_test_"))
    test_file = tmp_dir / "test_suno_song.mp3"

    try:
        subprocess.run([
            "ffmpeg", "-y",
            "-f", "lavfi", "-i", "anullsrc=r=44100:cl=mono",
            "-t", "1",
            "-metadata", "title=Test Song",
            "-metadata", "artist=Test Artist",
            "-metadata", "encoded_by=Suno AI v4",
            "-metadata", "comment=Generated by Suno AI",
            "-metadata", "encoder=Suno AI Inc.",
            str(test_file),
        ], capture_output=True, check=True)

        metadata = get_audio_metadata(test_file)
        logger.info(f"📋 原始元数据: {json.dumps(metadata, indent=2)}")

        keys, vals = detect_ai_tags(metadata)
        if keys:
            logger.info(f"🔍 检测到 {len(keys)} 个 AI 标记: {keys}")
        else:
            logger.warning("⚠️ 未检测到 AI 标记")

        out_file = tmp_dir / "test_cleaned.mp3"
        success = strip_metadata_via_ffmpeg(test_file, out_file)

        if success:
            clean_meta = get_audio_metadata(out_file)
            logger.info(f"📋 清理后元数据: {json.dumps(clean_meta, indent=2)}")
            ai_keys_after, _ = detect_ai_tags(clean_meta)
            if not ai_keys_after:
                logger.info("✅ 自检通过！AI 标记已全部清除")
            else:
                logger.warning(f"⚠️ 仍有残留 AI 标记: {ai_keys_after}")
        else:
            logger.error("❌ 自检失败")

    except Exception as e:
        logger.error(f"💥 自检异常: {e}")
        return False
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)
        logger.info("🧹 测试文件已清理")

    return True


