def check_ffmpeg() -> bool:
    """检查 ffmpeg 是否可用"""
    try:
        subprocess.run(
            ["ffmpeg", "-version"],
            capture_output=True,
            check=True,
        )
        return True
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False


def get_audio_metadata(file_path: Path) -> dict:
    """用 ffprobe 读取音频文件的元数据"""
    try:
        result = subprocess.run(
            [
                "ffprobe",
                "-v", "quiet",
                "-print_format", "json",
                "-show_format",
                "-show_streams",
                str(file_path),
            ],
            capture_output=True,
            encoding='utf-8', errors='replace',
            timeout=30,
        )
        data = json.loads(result.stdout)

        metadata = {}
        if "format" in data and "tags" in data["format"]:
            metadata.update(data["format"]["tags"])
        for stream in data.get("streams", []):
            if "tags" in stream:
                metadata.update(stream["tags"])

        return metadata
    except (subprocess.CalledProcessError, json.JSONDecodeError, TimeoutError) as e:
        logger.warning(f"无法读取元数据: {file_path.name} — {e}")
        return {}


def detect_ai_tags(file_or_metadata) -> Tuple[List[str], List[str]]:
    """
    智能检测元数据中的 AI 标记
    接受文件路径 (str/Path) 或已读取的元数据字典
    返回: (匹配的字段名列表, 匹配的字段值列表)
    """
    if isinstance(file_or_metadata, (str, Path)):
        metadata = get_audio_metadata(Path(file_or_metadata))
    elif isinstance(file_or_metadata, dict):
        metadata = file_or_metadata
    else:
        return [], []

    matched_keys = []
    matched_values = []
    for key, value in metadata.items():
        key_lower = key.lower()
        value_lower = str(value).lower()
        for kw in AI_KEYWORDS:
            if kw in key_lower or kw in value_lower:
                matched_keys.append(key)
                matched_values.append(f"{key} = {value}")
                break

    return matched_keys, matched_values


def strip_metadata_via_ffmpeg(
    input_path: Path,
    output_path: Path,
    keep_cover: bool = True,
) -> bool:
    """
    使用 ffmpeg 剥离元数据（暴力模式）
    """
    cmd = ["ffmpeg", "-y", "-i", str(input_path)]
    cmd.extend(["-map_metadata", "-1"])

    if keep_cover:
        cmd.extend(["-map", "0"])
    else:
        cmd.extend(["-map", "0:a"])

    cmd.extend([
        "-metadata", "encoded_by=",
        "-metadata", "encoder=",
        "-metadata", "comment=",
        "-metadata", "description=",
        "-metadata", "publisher=",
    ])

    cmd.extend(["-codec", "copy", str(output_path)])

    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            encoding='utf-8', errors='replace',
            timeout=120,
        )

        if result.returncode == 0 and output_path.exists() and output_path.stat().st_size > 0:
            logger.info(f"✅ ffmpeg 剥离成功: {input_path.name}")
            return True
        else:
            logger.error(f"❌ ffmpeg 剥离失败: {input_path.name} — {result.stderr[:200]}")
            return False

    except subprocess.TimeoutExpired:
        logger.error(f"⏰ 超时: {input_path.name}")
        return False
    except Exception as e:
        logger.error(f"💥 异常: {input_path.name} — {e}")
        return False


def strip_metadata_smart(input_path: Path, output_path: Path) -> bool:
    """
    智能模式：使用 mutagen 精确控制，只删除 AI 相关字段
    """
    try:
        import mutagen
        from mutagen.id3 import ID3, ID3NoHeaderError
        from mutagen.flac import FLAC
        from mutagen.mp4 import MP4
        from mutagen.oggvorbis import OggVorbis
        from mutagen.wave import WAVE
    except ImportError:
        logger.warning("mutagen 未安装，回退到 ffmpeg 暴力模式")
        return strip_metadata_via_ffmpeg(input_path, output_path, keep_cover=True)

    ext = input_path.suffix.lower()
    shutil.copy2(input_path, output_path)

    try:
        modified = False
        ai_fields_removed = []

        if ext == ".mp3":
            try:
                audio = ID3(output_path)
            except ID3NoHeaderError:
                audio = None
            if audio:
                frames_to_remove = []
                for frame_id in audio.keys():
                    frame_str = str(audio[frame_id])
                    for kw in AI_KEYWORDS:
                        if kw in frame_id.lower() or kw in frame_str.lower():
                            frames_to_remove.append(frame_id)
                            ai_fields_removed.append(f"{frame_id}: {frame_str[:80]}")
                            break
                for frame_id in frames_to_remove:
                    del audio[frame_id]
                    modified = True
                if modified:
                    audio.save(output_path)

        elif ext == ".flac":
            try:
                audio = FLAC(output_path)
                fields_to_remove = []
                for key in list(audio.keys()):
                    for kw in AI_KEYWORDS:
                        if kw in key.lower():
                            fields_to_remove.append(key)
                            ai_fields_removed.append(f"{key}: {audio[key]}")
                            break
                    else:
                        for val in audio.get(key, []):
                            if any(kw in str(val).lower() for kw in AI_KEYWORDS):
                                fields_to_remove.append(key)
                                ai_fields_removed.append(f"{key}: {audio[key]}")
                                break
                for field in fields_to_remove:
                    del audio[field]
                    modified = True
                if modified:
                    audio.save()
            except Exception:
                pass

        elif ext in (".m4a", ".mp4"):
            try:
                audio = MP4(output_path)
                fields_to_remove = []
                for key in list(audio.keys()):
                    for kw in AI_KEYWORDS:
                        if kw in key.lower() or kw in str(audio[key]).lower():
                            fields_to_remove.append(key)
                            ai_fields_removed.append(f"{key}: {audio[key]}")
                            break
                for field in fields_to_remove:
                    del audio[field]
                    modified = True
                if modified:
                    audio.save()
            except Exception:
                pass

        elif ext == ".ogg":
            try:
                audio = OggVorbis(output_path)
                fields_to_remove = []
                for key in list(audio.keys()):
                    for kw in AI_KEYWORDS:
                        if kw in key.lower():
                            fields_to_remove.append(key)
                            break
                    else:
                        if any(kw in str(val).lower() for val in audio.get(key, []) for kw in AI_KEYWORDS):
                            fields_to_remove.append(key)
                for field in fields_to_remove:
                    del audio[field]
                    modified = True
                if modified:
                    audio.save()
            except Exception:
                pass

        if ext == ".wav":
            return strip_metadata_via_ffmpeg(input_path, output_path)

        if modified:
            logger.info(f"🔍 [智能] 删除 {len(ai_fields_removed)} 个 AI 标记: {input_path.name}")
            for field in ai_fields_removed:
                logger.debug(f"  删除: {field}")
        else:
            logger.info(f"✅ [智能] 无 AI 标记: {input_path.name}")

        return True

    except Exception as e:
        logger.error(f"💥 [智能] 处理失败: {input_path.name} — {e}")
        output_path.unlink(missing_ok=True)
        return strip_metadata_via_ffmpeg(input_path, output_path, keep_cover=True)


def process_file(
    input_path: Path,
    output_dir: Path,
    mode: str = "ffmpeg",
    in_place: bool = False,
    keep_cover: bool = True,
    dry_run: bool = False,
) -> bool:
    """处理单个音频文件"""
    if input_path.suffix.lower() not in SUPPORTED_EXTENSIONS:
        logger.debug(f"跳过不支持格式: {input_path.name}")
        return False

    if dry_run:
        metadata = get_audio_metadata(input_path)
        if metadata:
            ai_keys, ai_vals = detect_ai_tags(metadata)
            if ai_keys:
                logger.info(f"🔍 [预览] {input_path.name} — 发现 {len(ai_keys)} 个 AI 标记:")
                for v in ai_vals:
                    logger.info(f"        {v}")
            else:
                logger.info(f"✅ [预览] {input_path.name} — 未发现 AI 标记")
        else:
            logger.info(f"ℹ️  [预览] {input_path.name} — 无元数据")
        return True

    if in_place:
        tmp_fd, tmp_path_str = tempfile.mkstemp(suffix=input_path.suffix)
        os.close(tmp_fd)
        output_path = Path(tmp_path_str)
        final_path = input_path
    else:
        output_path = output_dir / input_path.name
        final_path = output_path

    if mode == "smart":
        success = strip_metadata_smart(input_path, output_path)
    else:
        success = strip_metadata_via_ffmpeg(input_path, output_path, keep_cover)

    if success and in_place:
        shutil.move(str(output_path), str(final_path))
        logger.info(f"🔄 [原地] {input_path.name} 已更新")

    return success


def process_directory(
    input_dir: Path,
    output_dir: Path,
    mode: str = "ffmpeg",
    in_place: bool = False,
    keep_cover: bool = True,
    dry_run: bool = False,
    recursive: bool = False,
) -> Tuple[int, int]:
    """批量处理目录中的所有音频文件"""
    files = []
    glob_pattern = "**/*" if recursive else "*"

    for ext in SUPPORTED_EXTENSIONS:
        for f in input_dir.glob(f"{glob_pattern}{ext}"):
            if f.is_file():
                files.append(f)

    if not files:
        logger.warning(f"在 {input_dir} 中未找到支持的音频文件")
        return 0, 0

    logger.info(f"📂 找到 {len(files)} 个音频文件")

    if not dry_run and not in_place:
        output_dir.mkdir(parents=True, exist_ok=True)

    success_count = 0
    for i, file_path in enumerate(files, 1):
        logger.info(f"[{i}/{len(files)}] 处理: {file_path.name}")
        try:
            if process_file(
                input_path=file_path,
                output_dir=output_dir,
                mode=mode,
                in_place=in_place,
                keep_cover=keep_cover,
                dry_run=dry_run,
            ):
                success_count += 1
        except Exception as e:
            logger.error(f"处理 {file_path.name} 时出错: {e}")

    return success_count, len(files)


