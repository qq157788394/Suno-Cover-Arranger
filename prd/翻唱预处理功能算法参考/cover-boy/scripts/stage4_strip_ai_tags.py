def main():
    parser = argparse.ArgumentParser(
        description="🎵 Stage 4: 去除AI标记 — 批量剥离 Suno/AI 音频元数据",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
使用示例:
  %(prog)s -i ./suno_output -o ./cleaned
  %(prog)s -i ./suno_output --in-place
  %(prog)s -i ./suno_output --smart
  %(prog)s -i ./suno_output --dry-run
  %(prog)s --self-test
        """,
    )

    parser.add_argument("-i", "--input-dir", type=str, required=False,
                        help="输入目录（包含 Suno 输出的音频文件）")
    parser.add_argument("-o", "--output-dir", type=str, default=None,
                        help="输出目录（默认: input_dir/cleaned）")
    parser.add_argument("--in-place", action="store_true",
                        help="原地替换（直接修改原文件）")
    parser.add_argument("--smart", action="store_true",
                        help="智能模式（精确删除 AI 字段）")
    parser.add_argument("--no-cover", action="store_true",
                        help="不保留封面图")
    parser.add_argument("--recursive", action="store_true",
                        help="递归搜索子目录")
    parser.add_argument("--dry-run", action="store_true",
                        help="预览模式（只检测不处理）")
    parser.add_argument("--self-test", action="store_true",
                        help="运行自检")
    parser.add_argument("--verbose", "-v", action="store_true",
                        help="详细日志")

    args = parser.parse_args()

    if args.verbose:
        logger.setLevel(logging.DEBUG)

    if args.self_test:
        success = run_self_test()
        sys.exit(0 if success else 1)

    if not check_ffmpeg():
        msg = "❌ 需要 ffmpeg！请安装: https://ffmpeg.org/download.html"
        if sys.platform == "linux":
            msg += "\n   Linux: sudo apt install ffmpeg"
        logger.error(msg)
        sys.exit(1)

    if not args.input_dir:
        parser.print_help()
        logger.error("请指定输入目录 (-i) 或使用 --self-test")
        sys.exit(1)

    input_dir = Path(args.input_dir).expanduser().resolve()
    if not input_dir.exists():
        logger.error(f"❌ 目录不存在: {input_dir}")
        sys.exit(1)

    if args.in_place:
        output_dir = input_dir
    elif args.output_dir:
        output_dir = Path(args.output_dir).expanduser().resolve()
    else:
        output_dir = input_dir / "cleaned"

    mode = "smart" if args.smart else "ffmpeg"

    logger.info("=" * 60)
    logger.info("🎵 Stage 4: 去除AI标记")
    logger.info(f"📂 输入: {input_dir}")
    logger.info(f"📂 输出: {output_dir}")
    logger.info(f"⚙️  模式: {'智能' if mode == 'smart' else '暴力(ffmpeg)'}")
    logger.info(f"🖼️  保留封面: {'否' if args.no_cover else '是'}")
    logger.info(f"👀 预览: {'是' if args.dry_run else '否'}")
    logger.info("=" * 60)

    success, total = process_directory(
        input_dir=input_dir,
        output_dir=output_dir,
        mode=mode,
        in_place=args.in_place,
        keep_cover=not args.no_cover,
        dry_run=args.dry_run,
        recursive=args.recursive,
    )

    logger.info("=" * 60)
    if args.dry_run:
        logger.info(f"🔍 预览完成: {total} 个文件检查")
    else:
        logger.info(f"📊 结果: {success}/{total} 成功 | {total - success} 失败")
        if success == total:
            logger.info("🎉 全部搞定！")
    logger.info("=" * 60)


if __name__ == "__main__":
    main()
