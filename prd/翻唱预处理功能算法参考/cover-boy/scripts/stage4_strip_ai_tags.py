#!/usr/bin/env python3
"""
Stage 4: 去除AI标记 — 批量剥离 Suno/AI 生成的音频文件中的 AI 元数据标记

功能：
- 批量扫描目录下的音频文件（MP3/WAV/FLAC/OGG/M4A）
- 用 ffmpeg 剥离所有非音频元数据
- 可选保留封面图
- 可选仅删除特定 AI 标签字段（保留其他元数据）
- 智能模式：检测并仅删除 AI 相关字段
- 输出详细日志，记录每个文件的操作结果

用法：
    python stage4_strip_ai_tags.py -i /path/to/input/dir -o /path/to/output/dir
    python stage4_strip_ai_tags.py -i /path/to/input/dir --in-place   # 原地替换
    python stage4_strip_ai_tags.py -i /path/to/input/dir --smart     # 智能模式
    python stage4_strip_ai_tags.py -i /path/to/input/dir --dry-run   # 预览模式

兼容：独立运行 ｜ 集成到流水线 ｜ 作为 Python 模块 import
"""

import argparse
import json
import logging
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List, Optional, Tuple

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("strip_ai_tags")

# ============================================================================
# 配置
# ============================================================================

# Suno / AI 相关敏感关键词（用于智能模式检测）
AI_KEYWORDS = [
    "suno", "udio", "ai", "artificial intelligence", "generated by",
    "ai generated", "generated with", "powered by", "created by ai",
    "machine learning", "deep learning", "neural", "suno inc",
    "udio.com", "suno.ai", "suno ai", "audio-cleaner", "cleaner audio",
]

# 支持的文件格式
SUPPORTED_EXTENSIONS = {".mp3", ".wav", ".flac", ".ogg", ".m4a", ".aiff", ".wma"}


