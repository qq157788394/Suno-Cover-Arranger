class AITagStripper:
    """流水线集成类"""

    def __init__(self, mode: str = "ffmpeg", keep_cover: bool = True):
        self.mode = mode
        self.keep_cover = keep_cover
        self.stats = {"processed": 0, "success": 0, "ai_found": 0, "failed": 0}

    def process_file(self, input_path: str, output_path: str = None) -> bool:
        inp = Path(input_path)
        out = Path(output_path) if output_path else inp
        self.stats["processed"] += 1
        success = strip_metadata_via_ffmpeg(inp, out, self.keep_cover)
        if success:
            self.stats["success"] += 1
        else:
            self.stats["failed"] += 1
        return success

    def process_directory(self, input_dir: str, output_dir: str = None) -> dict:
        inp_dir = Path(input_dir)
        out_dir = Path(output_dir) if output_dir else inp_dir
        if out_dir != inp_dir:
            out_dir.mkdir(parents=True, exist_ok=True)
        success, total = process_directory(
            input_dir=inp_dir,
            output_dir=out_dir,
            mode=self.mode,
            keep_cover=self.keep_cover,
        )
        return {"total": total, "success": success, "failed": total - success}

    def get_stats(self) -> dict:
        return self.stats

    def reset_stats(self):
        self.stats = {"processed": 0, "success": 0, "ai_found": 0, "failed": 0}


